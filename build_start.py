#!/usr/bin/env python3
"""
build_start.py -- build a compact, box-fitting alpha-synuclein starting
structure for all-atom explicit-solvent MD (DESRES-protocol a99SB-disp).

Strategy (standard for long IDPs):
  1. Build a starting chain from sequence with ideal peptide geometry
     (PeptideBuilder). Default is a fully EXTENDED chain (phi=psi=180,
     PPII-compatible phi for prolines): clash-free by construction -- this
     is the published a99SB-disp IDP practice (Greener 2024, PMC10966991:
     explicit-solvent runs start from the collapsed product of an implicit
     run started from an extended conformation; 0.5 us burn-in discarded).
     --start-mode random gives the old basin-sampled random coil instead.
     Replica diversity comes from the seeded collapse dynamics (velocities
     + Langevin noise), not from the starting torsions.
  2. Add the C-terminal OXT oxygen (needed for C-terminal templates).
  3. Collapse in implicit solvent (OpenMM, amber14-all + GB-OBC2 by
     default) in chunks until the chain fits the target box
     (max CA-CA distance < fit_nm) -- a fully extended 140-mer spans
     ~30-50 nm and would crash through its own periodic image in the
     DESRES 160 A (16 nm) box.
     NOTE on the GB model: GBn2 (= AMBER igb=8) is the least numerically
     stable GB variant and detonated on ALL platforms (CPU included) for
     extended, highly charged starts (~24 formal charges on a 42 nm
     string) even after 5000 minimization steps + a 1 fs/100 K warm-up
     (seeds 1004/1005/1007, 2026-10-19). GB-OBC2 (igb=5) is the stable
     workhorse; the collapse model only manufactures a starting
     structure -- the explicit-solvent a99SB-disp physics is untouched.

The collapsed conformer is only a *starting structure*: explicit-solvent
equilibration and the first ns of production erase memory of the
collapse force field. Different seeds give different start classes --
use one seed per replica (this is your start-class control).

Usage:
  python3 build_start.py --seed 101 --out start.pdb
  python3 build_start.py --seed 102 --out start.pdb --box-nm 16 --max-collapse-ns 2

Deps: pip install PeptideBuilder biopython numpy openmm
"""
import argparse, io, os, sys

import numpy as np
from PeptideBuilder import Geometry, PeptideBuilder
import Bio.PDB

# Human alpha-synuclein, 140 aa (UniProt P37840)
ASYN_SEQ = ("MDVFMKGLSKAKEGVVAAAEKTKQGVAEAAGKTKEGVLYVGSKTKEGVVHGVATVAEKTKEQVTNVGG"
            "AVVTGVTAVAQKTVEGAGSIAAATGFVKKDQLGKNEEGAPQEGILEDMPVDPDNEAYEMPSEEGYQDYEPEA")

# Ramachandran basins for the expanded coil: (phi range, psi range, weight)
BASINS = [((-160.0, -100.0), (100.0, 170.0), 0.65),   # extended beta
          ((-95.0, -55.0),   (120.0, 170.0), 0.20),   # PPII
          ((-80.0, -50.0),   (-55.0, -25.0), 0.15)]   # alpha


def _sample_phipsi(rng):
    u = rng.random(); c = 0.0
    for (plo, phi), (pslo, pshi), w in BASINS:
        c += w
        if u <= c:
            return rng.uniform(plo, phi), rng.uniform(pslo, pshi)
    return -120.0, 130.0


def build_coil(seq, seed):
    """Expanded random-coil chain with ideal peptide geometry (heavy atoms)."""
    rng = np.random.default_rng(seed)
    phi, psi = _sample_phipsi(rng)
    g = Geometry.geometry(seq[0]); g.phi, g.psi, g.omega = phi, psi, 180.0
    st = PeptideBuilder.initialize_res(g)
    for aa in seq[1:]:
        phi, psi = _sample_phipsi(rng)
        g = Geometry.geometry(aa); g.phi, g.psi, g.omega = phi, psi, 180.0
        PeptideBuilder.add_residue(st, g)
    return st


def build_extended(seq):
    """Fully extended chain (phi=psi=180; proline gets PPII-compatible
    phi=-65/psi=145, which is still extended but ring-compatible).
    Clash-free by construction: no two atoms can coincide when the backbone
    is a straight zigzag. This is the published a99SB-disp IDP practice
    (Greener 2024 PMC10966991 starts every explicit run from the collapsed
    product of an implicit a99SB-disp+GBNeck2 run started from an extended
    conformation; Robustelli 2018 PNAS likewise avoids random-coil starts).
    Seed-independence is intentional: per-replica diversity is generated by
    the seeded velocities and Langevin noise of the collapse dynamics,
    which is also how the literature generates independent starts."""
    st = None
    for aa in seq:
        g = Geometry.geometry(aa)
        if aa == 'P':
            g.phi, g.psi = -65.0, 145.0
        else:
            g.phi, g.psi = 180.0, 180.0
        g.omega = 180.0
        if st is None:
            st = PeptideBuilder.initialize_res(g)
        else:
            PeptideBuilder.add_residue(st, g)
    return st


def _pdb_min_separation(pdb_path, seq_sep=3):
    """Min distance (Angstrom) between atoms at least seq_sep residues apart
    in sequence. A randomly built coil can place two residues nearly on top
    of each other; severe cases (exact coincidence) give infinite forces that
    NO minimizer or gentle dynamics can recover from -- seed 1004 NaN'd on
    every platform even after 5000 minimization steps and a 1 fs warm-up.
    Legit contacts between residues >=3 apart are >= ~2.4 A (1-4 bonded-path
    pairs), so anything under ~1.2 A is unambiguous pathology."""
    coords, rids = [], []
    with open(pdb_path) as fh:
        for l in fh:
            if l.startswith('ATOM'):
                rids.append(int(l[22:26]))
                coords.append([float(l[30:38]), float(l[38:46]),
                               float(l[46:54])])
    coords = np.asarray(coords)
    rids = np.asarray(rids)
    dmin = np.inf
    for i in range(len(coords)):
        far = np.abs(rids - rids[i]) >= seq_sep
        if far.any():
            d = np.linalg.norm(coords[far] - coords[i], axis=1)
            dmin = min(dmin, float(d.min()))
    return dmin


def _chain_dynamics_ok(chain_pdb, gb_model, fmax_tol=1e5, max_kj=1e8):
    """Direct 'will dynamics explode?' screen, v3. Build the EXACT collapse
    Hamiltonian (amber14 + GB, hydrogens added) on the CPU platform (always
    registered, always honest), minimize 1000 steps, then inspect FORCES --
    the quantity that actually detonates dynamics. v1 checked geometry,
    v2 checked energy; both passed the seed-1004 extended chain
    (+7.4e4 kJ/mol = ~30,000 kT of hidden strain) which then NaN'd every
    platform even after a 5000-step minimize + 100 K/1 fs warm-up: a local
    force singularity the minimizer cannot resolve explodes the first MD
    steps regardless of temperature or timestep. Post-minimization max |F|
    is the honest instrument, and on rejection the offending atom pair is
    printed -- failure becomes diagnosis. Returns (ok, energy_kj_per_mol)."""
    try:
        from openmm import app, unit, Platform, LangevinMiddleIntegrator
    except ImportError:
        print('[build_start] WARNING: openmm not importable; skipping '
              'chain dynamics screen')
        return True, float('nan')
    pdb = app.PDBFile(chain_pdb)
    ff = app.ForceField('amber14-all.xml', f'implicit/{gb_model}.xml')
    mod = app.Modeller(pdb.topology, pdb.positions)
    mod.addHydrogens(ff, pH=7.0)
    system = ff.createSystem(mod.topology, nonbondedMethod=app.NoCutoff,
                             constraints=app.HBonds)
    integ = LangevinMiddleIntegrator(300 * unit.kelvin, 1.0 / unit.picosecond,
                                     1.0 * unit.femtoseconds)
    sim = app.Simulation(mod.topology, system, integ,
                         Platform.getPlatformByName('CPU'))
    sim.context.setPositions(mod.positions)
    try:
        e0 = sim.context.getState(getEnergy=True).getPotentialEnergy()
        e0 = e0.value_in_unit(unit.kilojoule_per_mole)
        if not np.isfinite(e0) or e0 >= max_kj:
            return False, e0
        sim.minimizeEnergy(maxIterations=1000)
        st1 = sim.context.getState(getEnergy=True, getForces=True,
                                   getPositions=True)
        e1 = st1.getPotentialEnergy().value_in_unit(unit.kilojoule_per_mole)
        f1 = st1.getForces(asNumpy=True).value_in_unit(
            unit.kilojoule_per_mole / unit.nanometer)
        enorm = np.linalg.norm(f1, axis=1)
        fmax = float(enorm.max())
        if not np.isfinite(e1) or not np.isfinite(fmax):
            return False, e1
        if fmax >= fmax_tol:
            # report the offender and its nearest nonbonded neighbour
            ats = list(mod.topology.atoms())
            i = int(enorm.argmax())
            a = ats[i]
            pos = st1.getPositions(asNumpy=True).value_in_unit(unit.nanometer)
            rid = np.array([int(x.residue.id) for x in ats])
            d = np.linalg.norm(pos - pos[i], axis=1)
            d[(np.abs(rid - rid[i]) <= 1)] = np.inf   # skip bonded neighbours
            j = int(d.argmin())
            b = ats[j]
            print(f'[build_start] force pathology: max |F| = {fmax:.3g} '
                  f'kJ/mol/nm at {a.name} {a.residue.name} {a.residue.id}; '
                  f'nearest nonbonded: {b.name} {b.residue.name} '
                  f'{b.residue.id} at {d[j] * 10:.2f} A')
            return False, e1
        return True, e1
    except Exception:
        return False, float('nan')


def _pdb_text(structure):
    out = Bio.PDB.PDBIO(); out.set_structure(structure)
    buf = io.StringIO(); out.save(buf)
    return buf.getvalue()


def add_oxt(pdb_txt):
    """Add the C-terminal OXT oxygen by reflecting C->O across the C->CA axis
    (standard planar carboxyl geometry). Without it, template matching fails
    on the last residue in both OpenMM and pdb2gmx."""
    lines = pdb_txt.splitlines()
    atoms = [(i, l) for i, l in enumerate(lines) if l.startswith("ATOM")]
    last_res = atoms[-1][1][22:26]
    ra = [(i, l) for i, l in atoms if l[22:26] == last_res]
    pos = {}
    for i, l in ra:
        pos[l[12:16].strip()] = (i, np.array([float(l[30:38]),
                                              float(l[38:46]),
                                              float(l[46:54])]))
    a = pos['CA'][1] - pos['C'][1]
    b = pos['O'][1] - pos['C'][1]
    a_hat = a / np.linalg.norm(a)
    d = b / np.linalg.norm(b)
    refl = 2.0 * np.dot(d, a_hat) * a_hat - d
    oxt = pos['C'][1] + 1.25 * refl / np.linalg.norm(refl)
    serial = int(atoms[-1][1][6:11]) + 1
    iC, _ = pos['C']
    lC = lines[iC]
    oxt_line = (f"ATOM  {serial:5d}  OXT {lC[17:27]}   "
                f"{oxt[0]:8.3f}{oxt[1]:8.3f}{oxt[2]:8.3f}  1.00  0.00           O  ")
    out = []
    for i, l in enumerate(lines):
        out.append(l)
        if i == pos['CB'][0]:
            out.append(oxt_line)
    return "\n".join(out) + "\n"


def ca_geometry(pdb_path):
    """Return (Rg nm, max CA-CA distance nm, n_CA)."""
    xyz = []
    with open(pdb_path) as fh:
        for l in fh:
            if l.startswith("ATOM") and l[12:16].strip() == "CA":
                xyz.append([float(l[30:38]), float(l[38:46]), float(l[46:54])])
    xyz = np.array(xyz) / 10.0
    rg = float(np.sqrt(((xyz - xyz.mean(0)) ** 2).sum(1).mean()))
    # pairwise max without scipy
    d2max = 0.0
    for i in range(len(xyz)):
        d2 = ((xyz[i + 1:] - xyz[i]) ** 2).sum(1)
        if len(d2):
            d2max = max(d2max, float(d2.max()))
    return rg, float(np.sqrt(d2max)), len(xyz)


def collapse(pdb_in, pdb_out, seed, chunk_ps, gb_model, platform_name):
    """Run one implicit-solvent collapse chunk; returns None.

    Platform handling is fail-soft: 'auto' tries CUDA -> OpenCL -> CPU, but a
    platform is only accepted after a real Context has been built AND a chunk
    step has run -- a registered-but-broken plugin (e.g. conda-forge OpenMM
    whose CUDA kernels are newer than the node driver ->
    CUDA_ERROR_UNSUPPORTED_PTX_VERSION) falls through to the next candidate
    instead of killing the setup.

    NaN handling: every chunk is pre-conditioned -- a hard 5000-step
    minimization followed by a two-stage cold warm-up (10 ps at 100 K,
    then 5 ps at 200 K, both at 1 fs) before the real 300 K / 2 fs chunk.
    Dropping an extended, multiply-charged chain straight into 300 K
    dynamics is a Coulomb shock that can NaN even a well-posed GB model;
    the ramp costs seconds and makes the collapse boring. Each platform
    gets up to 3 attempts with re-seeded velocities. The chunk is verified
    finite BEFORE writing, and the PDB is written atomically (tmp +
    rename) so a crash mid-write can never leave a truncated start
    structure that a later adopt-check might mistake for a collapsed one."""
    from openmm import app, unit, LangevinMiddleIntegrator, Platform
    candidates = (['CUDA', 'OpenCL', 'CPU'] if platform_name == 'auto'
                  else [platform_name])
    pdb = app.PDBFile(pdb_in)
    ff = app.ForceField('amber14-all.xml', f'implicit/{gb_model}.xml')
    mod = app.Modeller(pdb.topology, pdb.positions)
    if not getattr(collapse, '_hydrated', False):
        mod.addHydrogens(ff, pH=7.0)
        collapse._hydrated = True
    system = ff.createSystem(mod.topology, nonbondedMethod=app.NoCutoff,
                             constraints=app.HBonds)
    errs = []
    for cand in candidates:
        try:
            platform = Platform.getPlatformByName(cand)
        except Exception as e:
            errs.append(f'{cand}: not registered ({e})')
            continue
        for attempt in range(3):
            seed_a = seed + 7919 * attempt
            start_pos = mod.positions
            try:
                # unconditional pre-conditioning: hard minimize, then a
                # two-stage cold ramp (100 K -> 200 K, 1 fs) before the
                # real 300 K / 2 fs chunk
                integ0 = LangevinMiddleIntegrator(100 * unit.kelvin,
                                                  1.0 / unit.picosecond,
                                                  1.0 * unit.femtoseconds)
                integ0.setRandomNumberSeed(seed_a)
                try:
                    sim0 = app.Simulation(mod.topology, system, integ0,
                                          platform)
                except Exception as e:
                    # registered-but-broken platform (e.g. CUDA PTX mismatch):
                    # retrying is pointless -- move to the next candidate
                    errs.append(f'{cand}: init failed ({type(e).__name__})')
                    print(f'[build_start] platform {cand} unusable '
                          f'({errs[-1]}); trying next')
                    break
                sim0.context.setPositions(mod.positions)
                sim0.context.setVelocitiesToTemperature(100 * unit.kelvin,
                                                        seed_a)
                sim0.minimizeEnergy(maxIterations=5000)
                sim0.step(10000)  # 10 ps at 1 fs / 100 K
                integ0.setTemperature(200 * unit.kelvin)
                sim0.context.setVelocitiesToTemperature(200 * unit.kelvin,
                                                        seed_a + 1)
                sim0.step(5000)   # 5 ps at 1 fs / 200 K
                st0 = sim0.context.getState(getPositions=True)
                pos0 = st0.getPositions(asNumpy=True)
                if not np.isfinite(
                        pos0.value_in_unit(unit.nanometer)).all():
                    raise ValueError('NaN/inf positions after warm-up')
                start_pos = pos0
                del sim0, integ0
                integ = LangevinMiddleIntegrator(300 * unit.kelvin,
                                                 1.0 / unit.picosecond,
                                                 2.0 * unit.femtoseconds)
                integ.setRandomNumberSeed(seed_a)
                try:
                    sim = app.Simulation(mod.topology, system, integ,
                                         platform)
                except Exception as e:
                    # Context construction failed (e.g. a registered but
                    # broken CUDA plugin: CUDA_ERROR_UNSUPPORTED_PTX_VERSION).
                    # Retrying the same platform is pointless -- move on.
                    errs.append(f'{cand}: init failed ({type(e).__name__} '
                                f'{str(e).strip().splitlines()[-1] if str(e).strip() else e})')
                    print(f'[build_start] platform {cand} unusable '
                          f'({errs[-1]}); trying next')
                    break
                sim.context.setPositions(start_pos)
                sim.context.setVelocitiesToTemperature(300 * unit.kelvin,
                                                       seed_a)
                sim.step(int(chunk_ps * 1000 / 2.0))
                st = sim.context.getState(getPositions=True, getEnergy=True)
                pe = st.getPotentialEnergy().value_in_unit(
                    unit.kilojoule_per_mole)
                pos = st.getPositions(asNumpy=True)
                if not np.isfinite(pe) or not np.isfinite(
                        pos.value_in_unit(unit.nanometer)).all():
                    raise ValueError(f'NaN/inf in chunk (Epot={pe})')
                tmp_out = pdb_out + '.tmp'
                with open(tmp_out, 'w') as f:
                    app.PDBFile.writeFile(mod.topology, st.getPositions(), f)
                os.replace(tmp_out, pdb_out)
            except Exception as e:
                errs.append(f'{cand}/try{attempt}: {type(e).__name__} '
                            f'{str(e).strip().splitlines()[-1] if str(e).strip() else e}')
                nxt = ('retrying with re-seeded velocities'
                       if attempt < 2 else f'giving up on {cand}')
                print(f'[build_start] collapse failed ({errs[-1]}); {nxt}')
                continue
            if cand != candidates[0] or len(candidates) > 1:
                print(f'[build_start] collapse running on platform: {cand}')
            if attempt:
                print(f'[build_start] chunk recovered on attempt '
                      f'{attempt + 1}')
            return
    sys.exit('[build_start] no usable OpenMM platform: ' + ' | '.join(errs))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--seed', type=int, required=True,
                    help='per-replica seed (use the replica index)')
    ap.add_argument('--out', required=True, help='output PDB (compact start)')
    ap.add_argument('--box-nm', type=float, default=16.0,
                    help='target cubic box edge (DESRES protocol: 16 nm = 160 A)')
    ap.add_argument('--fit-margin-nm', type=float, default=2.0,
                    help='required clearance: max CA-CA must be < box - margin')
    ap.add_argument('--chunk-ps', type=float, default=200.0,
                    help='implicit-solvent collapse chunk between geometry checks')
    ap.add_argument('--max-collapse-ns', type=float, default=2.0,
                    help='give up if not collapsed after this much implicit MD')
    ap.add_argument('--gb-model', default='obc2',
                    choices=['gbn2', 'gbn', 'obc2', 'obc1', 'hct'],
                    help='implicit model for the collapse (start only). '
                         'Default obc2: GBn2 (= AMBER igb=8) detonated on '
                         'extended charged starts on every platform; obc2 '
                         '(igb=5) is the stable workhorse')
    ap.add_argument('--platform', default='auto',
                    choices=['auto', 'CUDA', 'OpenCL', 'CPU'],
                    help='OpenMM platform for the collapse (default auto: '
                         'CUDA -> OpenCL -> CPU)')
    ap.add_argument('--start-mode', default='extended',
                    choices=['extended', 'random'],
                    help="extended (default): clash-free extended chain, "
                         "diversity from seeded collapse dynamics (published "
                         "a99SB-disp IDP practice); random: basin-sampled "
                         "coil, diversity from starting torsions")
    ap.add_argument('--keep-coil', action='store_true',
                    help='also write the pre-collapse expanded coil to <out>.coil.pdb')
    args = ap.parse_args()

    fit_nm = args.box_nm - args.fit_margin_nm
    # Build a start chain that survives TWO screens before any dynamics:
    #   1. geometric: no two heavy atoms >=3 residues apart closer than 1.2 A
    #   2. dynamical: minimize 1000 steps under the real collapse Hamiltonian
    #      and demand gentle POST-MINIMIZATION FORCES (max |F| < 1e5
    #      kJ/mol/nm) -- energy lies, forces do not. On rejection the
    #      offending atom pair is printed.
    # Extended starts are clash-free by construction, so the screens should
    # pass on the first draw; random coils may need resampling. Derived
    # resample seeds (seed*1000+k) are deterministic and printed.
    coil_path = args.out + '.coil.pdb'
    seed_used = args.seed
    for k in range(8):
        seed_used = args.seed if k == 0 else args.seed * 1000 + k
        if args.start_mode == 'extended' and k == 0:
            chain = build_extended(ASYN_SEQ)
            mode = 'extended'
        else:
            chain = build_coil(ASYN_SEQ, seed_used)
            mode = 'random coil'
        coil_txt = add_oxt(_pdb_text(chain))
        with open(coil_path, 'w') as f:
            f.write(coil_txt)
        dmin = _pdb_min_separation(coil_path)
        if dmin < 1.2:
            print(f'[build_start] {mode} clash: atoms >=3 residues apart only '
                  f'{dmin:.2f} A (seed {seed_used}); resampling')
            continue
        eok, pe = _chain_dynamics_ok(coil_path, args.gb_model)
        if not eok:
            print(f'[build_start] {mode} dynamics screen failed '
                  f'(Epot={pe:.3g} kJ/mol, seed {seed_used}); resampling')
            continue
        print(f'[build_start] {mode} screens passed: minSep={dmin:.2f} A, '
              f'post-min Epot={pe:.3g} kJ/mol, forces gentle '
              f'(seed {seed_used})')
        break
    else:
        sys.exit('[build_start] could not build a clash-free start in 8 '
                 'draws -- investigate the chain builder')
    if seed_used != args.seed:
        print(f'[build_start] NOTE: coil seed {seed_used} used instead of '
              f'{args.seed} (clash/energy resample) -- this line is the provenance')
    rg, dmax, n = ca_geometry(coil_path)
    print(f'[build_start] expanded coil: {n} residues, Rg={rg:.2f} nm, '
          f'maxDist={dmax:.2f} nm (target fit < {fit_nm:.2f} nm)')

    done = dmax < fit_nm
    elapsed_ps = 0.0
    cur = coil_path
    while not done and elapsed_ps < args.max_collapse_ns * 1000.0:
        collapse(cur, args.out, seed=args.seed + int(elapsed_ps),
                 chunk_ps=args.chunk_ps, gb_model=args.gb_model,
                 platform_name=args.platform)
        elapsed_ps += args.chunk_ps
        rg, dmax, n = ca_geometry(args.out)
        print(f'[build_start] collapse {elapsed_ps:7.0f} ps: Rg={rg:.2f} nm, '
              f'maxDist={dmax:.2f} nm')
        done = dmax < fit_nm
        cur = args.out

    if not done:
        sys.exit(f'[build_start] chain still spans {dmax:.1f} nm after '
                 f'{args.max_collapse_ns} ns of collapse; increase '
                 f'--max-collapse-ns or use a larger --box-nm.')

    if not args.keep_coil and os.path.exists(coil_path):
        os.remove(coil_path)
    rg, dmax, n = ca_geometry(args.out)
    print(f'[build_start] wrote {args.out}: {n} residues, Rg={rg:.2f} nm, '
          f'maxDist={dmax:.2f} nm -- fits {args.box_nm:.0f} nm box.')


if __name__ == '__main__':
    main()
